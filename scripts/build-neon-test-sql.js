const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const directory = path.join(root, 'backend/database/migrations');
const files = fs.readdirSync(directory).filter(name => /^\d{3}_.*\.sql$/.test(name)).sort();
if (files.length !== 10) throw new Error('Review migration list before generating bootstrap');
const bodies = files.map(name => {
 const sql = fs.readFileSync(path.join(directory, name), 'utf8');
 if ((sql.match(/^BEGIN;\r?$/gm)||[]).length !== 1 || (sql.match(/^COMMIT;\r?$/gm)||[]).length !== 1) throw new Error('Unexpected transaction structure: '+name);
 return '-- Migration: '+name+'\n'+sql.replace(/^(BEGIN;|COMMIT;)\r?$/gm, '');
});
const sql = `-- GENERATED by scripts/build-neon-test-sql.js. EMPTY TEST DATABASE ONLY.
-- Run the entire file once in Neon SQL Editor. No credentials are needed here.
-- All migrations are atomic. Existing application schemas are rejected.
BEGIN;
SET LOCAL ai_latency.environment = 'test';
DO $$ BEGIN
 IF EXISTS (SELECT 1 FROM pg_namespace WHERE nspname = 'ai_latency_private') THEN
  RAISE EXCEPTION 'Application schema already exists; do not rerun bootstrap';
 END IF;
END $$;
${bodies.join('\n\n')}
COMMIT;
SELECT environment, schema_version FROM ai_latency_private.deployment_context WHERE singleton = true;
`;
fs.writeFileSync(path.join(root, 'deploy/neon-test-init.sql'), sql);
console.log('Generated deploy/neon-test-init.sql from '+files.length+' migrations');
